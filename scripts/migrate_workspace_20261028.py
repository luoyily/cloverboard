"""One-off migration from the October 27 workspace format to October 28.

Stop servers using this workspace before applying. Preview by default:
    python scripts/migrate_workspace_20261028.py ./runs
    python scripts/migrate_workspace_20261028.py ./runs --apply

Only .workspace/workspace.sqlite is migrated; training databases are untouched.
Manual colors become fixed colors. Legacy automatic colors are regenerated by
the current frontend rather than retaining the removed slot/seed algorithm.
"""

import argparse
from contextlib import closing
from datetime import datetime, timezone
import json
from pathlib import Path
import sqlite3
import sys
from uuid import uuid4

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from pydantic import ValidationError

from cloverboard.server.models import PaletteLibrary, RunColor, SavedView, WorkspaceSave, WorkspaceState


class MigrationError(ValueError):
    """The workspace cannot be safely migrated by this one-off script."""


def _object(value, label):
    if not isinstance(value, dict):
        raise MigrationError(f"{label} must be a JSON object")
    return value


def _json(value, label):
    try:
        return _object(json.loads(value), label)
    except (TypeError, json.JSONDecodeError) as error:
        raise MigrationError(f"Invalid JSON in {label}") from error


def _dump(value):
    return json.dumps(value, ensure_ascii=False, allow_nan=False, separators=(",", ":"))


def _singleton(connection, table):
    # Table names are constants supplied only by _plan.
    rows = connection.execute(f"SELECT id, payload FROM {table}").fetchall()
    if len(rows) > 1 or (rows and rows[0][0] != 1):
        raise MigrationError(f"Unexpected rows in {table}")
    return _json(rows[0][1], table) if rows else None


def _state(value, label, report):
    state = dict(_object(value, label))
    if "chart_zoom" in state:
        state.pop("chart_zoom")
        report["zoom_states_removed"] += 1
    if "colors" in state:
        colors = dict(_object(state["colors"], f"{label}.colors"))
        if "overrides" in colors or "assignments" in colors:
            overrides = _object(colors.pop("overrides", {}), f"{label}.colors.overrides")
            _object(colors.pop("assignments", {}), f"{label}.colors.assignments")
            runs = dict(_object(colors.get("runs", {}), f"{label}.colors.runs"))
            for key, color in overrides.items():
                entry = RunColor.model_validate({"color": color, "fixed": True})
                if key not in runs:
                    runs[key] = {"color": entry.color.lower(), "fixed": True}
                    report["manual_colors_migrated"] += 1
            colors["runs"] = runs
            report["automatic_colors_will_regenerate"] = True
        state["colors"] = colors
    if "targets" in state:
        targets = dict(_object(state["targets"], f"{label}.targets"))
        for metric, target in targets.items():
            target = _object(target, f"{label}.targets[{metric!r}]")
            if "value" in target and "items" not in target:
                if set(target) - {"value", "direction"}:
                    raise MigrationError(f"Unknown legacy target fields in {label}: {metric}")
                targets[metric] = {
                    "items": [{"id": "migrated", "name": "Target", "chart_label": "",
                               "value": target["value"], "direction": target.get("direction", "gte")}],
                    "active_id": "migrated",
                }
                report["targets_migrated"] += 1
        state["targets"] = targets
    # Reject unknown formats or invalid settings instead of silently resetting them.
    return WorkspaceState.model_validate(state).model_dump(mode="json", exclude_unset=True)


def _plan(connection, report):
    tables = {row[0] for row in connection.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    if not {"workspace_state", "views"}.issubset(tables) or not tables.intersection({"color_registry", "palette_library"}):
        raise MigrationError("Not a supported workspace database; do not pass a run.sqlite file")
    check = connection.execute("PRAGMA quick_check").fetchall()
    if check != [("ok",)]:
        raise MigrationError(f"SQLite integrity check failed: {check}")

    legacy = _singleton(connection, "color_registry") if "color_registry" in tables else None
    current = _singleton(connection, "palette_library") if "palette_library" in tables else None
    old_palettes = PaletteLibrary.model_validate({"palettes": legacy.get("palettes", [])} if legacy else {})
    new_palettes = PaletteLibrary.model_validate(current or {})
    # A partially upgraded workspace may already contain newer palette edits.
    palettes = {palette.id: palette for palette in new_palettes.palettes}
    for palette in old_palettes.palettes:
        palettes.setdefault(palette.id, palette)
    library = PaletteLibrary(palettes=list(palettes.values())).model_dump(mode="json")
    library_changed = "palette_library" not in tables or (
        current != library if current is not None else bool(library["palettes"])
    )
    library_update = library if library_changed else None

    saved = _singleton(connection, "workspace_state")
    state_update = None
    if saved is not None:
        if "state" not in saved:
            raise MigrationError("workspace_state is missing its state")
        converted = {**saved, "state": _state(saved["state"], "workspace_state", report)}
        converted = WorkspaceSave.model_validate(converted).model_dump(mode="json", exclude_unset=True)
        if converted != saved:
            state_update = converted

    views = []
    for view_id, name, raw in connection.execute("SELECT view_id, name, state FROM views ORDER BY rowid"):
        original = _json(raw, f"View {name!r}")
        state = _state(original, f"View {name!r}", report)
        SavedView(view_id=view_id, name=name, state=state)
        if state != original:
            views.append((_dump(state), view_id))
    report["views_updated"] = len(views)
    report["legacy_registry_removed"] = "color_registry" in tables
    report["automatic_colors_will_regenerate"] |= "color_registry" in tables
    return state_update, views, library_update


def _backup(path):
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    backup = path.with_name(f"{path.name}.bak-{stamp}-{uuid4().hex[:8]}")
    # Reserve an exclusive filename and copy through SQLite, including WAL data.
    with backup.open("xb"):
        pass
    try:
        with closing(sqlite3.connect(f"{path.as_uri()}?mode=ro", uri=True)) as source:
            with closing(sqlite3.connect(backup)) as destination:
                source.backup(destination)
    except BaseException:
        backup.unlink(missing_ok=True)
        raise
    return backup


def migrate(path: Path, *, apply: bool = False) -> dict:
    path = Path(path).expanduser()
    if path.is_dir():
        path = path / ".workspace" / "workspace.sqlite"
    path = path.resolve()
    if not path.is_file():
        raise MigrationError(f"Workspace database does not exist: {path}")
    report = {
        "database": str(path), "changed": False, "applied": False, "backup": None,
        "views_updated": 0, "manual_colors_migrated": 0, "targets_migrated": 0,
        "zoom_states_removed": 0, "legacy_registry_removed": False,
        "automatic_colors_will_regenerate": False,
    }
    mode = "rw" if apply else "ro"
    try:
        with closing(sqlite3.connect(f"{path.as_uri()}?mode={mode}", uri=True, timeout=5)) as connection:
            try:
                connection.execute("BEGIN IMMEDIATE" if apply else "BEGIN")
                state, views, library = _plan(connection, report)
                report["changed"] = state is not None or bool(views) or library is not None or report["legacy_registry_removed"]
                if not apply or not report["changed"]:
                    connection.rollback()
                    return report
                # The write lock keeps the previewed snapshot stable through backup
                # and commit. A separate reader backs up the committed old database.
                report["backup"] = str(_backup(path))
                if library is not None:
                    connection.execute("CREATE TABLE IF NOT EXISTS palette_library (id INTEGER PRIMARY KEY CHECK (id=1), payload TEXT NOT NULL)")
                    connection.execute("INSERT OR REPLACE INTO palette_library VALUES (1, ?)", (_dump(library),))
                if state is not None:
                    connection.execute("UPDATE workspace_state SET payload=? WHERE id=1", (_dump(state),))
                connection.executemany("UPDATE views SET state=? WHERE view_id=?", views)
                if report["legacy_registry_removed"]:
                    connection.execute("DROP TABLE color_registry")
                connection.commit()
                report["applied"] = True
            except BaseException:
                connection.rollback()
                raise
    except (sqlite3.Error, OSError, ValidationError, ValueError) as error:
        suffix = f"; original backup: {report['backup']}" if report["backup"] else ""
        raise MigrationError(f"Migration refused or rolled back: {error}{suffix}") from error
    return report


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("path", type=Path, help="Log directory or its .workspace/workspace.sqlite file")
    parser.add_argument("--apply", action="store_true", help="Back up and apply the migration (default: preview only)")
    args = parser.parse_args(argv)
    try:
        print(json.dumps(migrate(args.path, apply=args.apply), indent=2, ensure_ascii=False))
    except MigrationError as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
